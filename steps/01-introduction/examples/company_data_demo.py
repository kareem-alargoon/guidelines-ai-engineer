"""
company_data_demo.py — ليه الموديل "ميعرفش" داتا شركتك، وإزاي RAG بيحل ده.

بنسأل نفس السؤال مرتين:
  1) من غير أي معلومات      ← الموديل هيقول مش عارف، أو هيألّف إجابة (hallucination)
  2) ومعاه المستند المناسب  ← يجاوب صح من المستند

المرة التانية هي فكرة RAG في أبسط صورة. RAG الحقيقي (Step 09) بيضيف بس
خطوة "دوّر على المستند المناسب أوتوماتيك" وسط آلاف المستندات.

التشغيل:
    python company_data_demo.py
"""

import sys

from local_llm import MODEL, LocalLLMError, chat

# مستند داخلي من شركة وهمية — الموديل عمره ما شافه وقت التدريب
HR_POLICY = """\
سياسة الموظفين — شركة نيلوس للبرمجيات (تحديث 2026)
- الإجازة السنوية: 24 يوم عمل، وتزيد لـ 30 يوم بعد 5 سنين في الشركة.
- الشغل من البيت: مسموح يومين في الأسبوع (الثلاثاء والخميس).
- اللابتوب: الشركة بتسلّم كل موظف لابتوب، ويتغيّر كل 3 سنين.
"""

QUESTION = "في شركة نيلوس للبرمجيات، كام يوم إجازة سنوية ليا، وأقدر أشتغل من البيت أنهي أيام؟"


def main() -> None:
    print(f"🧠 model: {MODEL}\n❓ {QUESTION}\n")
    try:
        # ── 1) من غير context ──────────────────────────────────────
        print("━━━ 1) من غير أي مستند ━━━")
        print(chat([{"role": "user", "content": QUESTION}]))

        # ── 2) مع المستند في الـ prompt ─────────────────────────────
        print("\n━━━ 2) مع المستند (فكرة RAG) ━━━")
        messages = [
            {
                "role": "system",
                "content": (
                    "جاوب من المستند اللي بين <document> بس. "
                    "لو الإجابة مش موجودة فيه قول: مش موجود في المستند.\n\n"
                    f"<document>\n{HR_POLICY}</document>"
                ),
            },
            {"role": "user", "content": QUESTION},
        ]
        print(chat(messages))
    except LocalLLMError as e:
        sys.exit(f"❌ {e}")

    print("\n💡 الموديل ماتدرّبش على المستند — إحنا بس حطيناه في الـ prompt وقت السؤال.")


if __name__ == "__main__":
    main()
